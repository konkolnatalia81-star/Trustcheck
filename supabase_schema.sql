create table if not exists public.trust_submissions (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  nickname text not null default '',
  answers jsonb not null,
  score integer,
  scored_answers integer not null default 0,
  custom_answers integer not null default 0,
  category_scores jsonb not null default '[]'::jsonb
);

alter table public.trust_submissions enable row level security;
revoke all on public.trust_submissions from anon, authenticated;
